#!/bin/bash
# Derive the EL0 / MMU-on isla config from Islaris c978e10f's
# etc/aarch64_isla_coq.toml (EL2, MMU off).  Only these values change:
#   PSTATE.EL  0b10 -> 0b00   (EL0, user process)
#   PSTATE.SP  0b1  -> 0b0    (EL0 always uses SP_EL0)
#   SCTLR_EL1  0x4000002 -> 0x2034f4d91d
#              Linux arm64 INIT_SCTLR_EL1_MMU_ON bits that exist in Armv8.5:
#              M C SA SA0 SED EOS I DZE UCT nTWE TSCXT IESB EIS SPAN UCI
#              nTLSMD LSMAOE ITFSB.  M=1: stage-1 translation ON for EL1&0.
#   TCR_EL1    0 -> 0x35b5103510
#              4K granules, T0SZ=T1SZ=16 (48-bit VA), WBWA inner-shareable
#              walks, IPS=48 bit, AS=1 (16-bit ASID), TBI0=1 (top byte
#              ignored for user addresses), as Linux defconfig sets it.
# HCR_EL2 stays 0x80000000 (RW=1, E2H=0, TGE=0): the non-VHE profile, where
# EL0 is translated by the EL1&0 regime.  TTBR0_EL1 and MAIR_EL1 are left
# unconstrained, so a translation-table walk reads symbolic memory.
#   mk-el0-config.sh ISLARIS_SRC > aarch64_isla_coq_el0_linux.toml
set -euo pipefail
src="$1/etc/aarch64_isla_coq.toml"
echo "f62e62f3269e06e2f2ae07452cc0a4bfc7c4e465398ed75b615cc63de4f507a9  $src" | sha256sum -c --quiet -
echo '# GENERATED by ports/arm/islaris/etc/mk-el0-config.sh from Islaris c978e10f'
echo '# etc/aarch64_isla_coq.toml: EL0, stage-1 MMU on (Linux non-VHE profile).'
sed -e 's/^"PSTATE.EL" = "0b10"$/"PSTATE.EL" = "0b00"/' \
    -e 's/^"PSTATE.SP" = "0b1"$/"PSTATE.SP" = "0b0"/' \
    -e 's/^"SCTLR_EL1" = "0x0000000004000002"$/"SCTLR_EL1" = "0x0000002034f4d91d"/' \
    -e 's/^"TCR_EL1" = "0x0000000000000000"$/"TCR_EL1" = "0x00000035b5103510"/' "$src"
