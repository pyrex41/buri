"""E2E-22 (chezprim lane): package the raw nanopass capture as bytes only.

This script never decides validity.  It copies the np-trace section of
ports/chez-np/tarm64le-buri-arm-add.raw.np into Rocq string literals, cut at
each tracer header "output of NAME:" and, inside a section, at the patched
tracer's "raw output:" line.  scripts/check-chez-prim-package.py checks that
the pieces reassemble the trace byte for byte; Rocq (rocq/ChezPrim*.v) reads
and checks the text itself.

usage: package-chez-prim.py TRACE.raw.np OUT-Input.v
"""
from pathlib import Path
import hashlib
import re
import sys

HEADER = re.compile(r'^output of (.*):$')
RAW = 'raw output:\n'


def coq_string(text):
    assert all(ord(c) < 128 for c in text), 'non-ASCII input'
    return '"' + text.replace('"', '""') + '"'


def split_trace(text):
    out = []
    for line in text.splitlines(keepends=True):
        m = HEADER.match(line.rstrip('\n'))
        if m and line.endswith('\n'):
            out.append([m.group(1), ''])
        else:
            assert out, 'text before the first header'
            out[-1][1] += line
    res = []
    for name, body in out:
        if body.count(RAW) == 0:
            res.append((name, body, None))
        else:
            # the raw marker is a whole line; split at its first occurrence
            i = body.index(RAW)
            assert i == 0 or body[i - 1] == '\n'
            res.append((name, body[:i], body[i + len(RAW):]))
    return res


def main(trace, out):
    raw = Path(trace).read_bytes()
    t = raw.decode('ascii')
    start = t.index('@@@ np-trace\n') + len('@@@ np-trace\n')
    end = t.index('@@@ end\n', start)
    params = t[t.index('@@@ parameters\n') + len('@@@ parameters\n'):t.index('@@@ end\n')]
    secs = split_trace(t[start:end])

    def opt(x):
        return 'None' if x is None else '(Some ' + coq_string(x) + ')'
    Path(out).write_text(
        '(* Generated by scripts/package-chez-prim.py: exact captured text, packaging only.\n'
        '   raw_sections: the np-trace section of ports/chez-np/tarm64le-buri-arm-add.raw.np\n'
        '   (sha256 ' + hashlib.sha256(raw).hexdigest() + ')\n'
        '   cut at each tracer header "output of NAME:" and at the patched tracer\'s\n'
        '   "raw output:" line; scripts/check-chez-prim-package.py checks that the pieces\n'
        '   reassemble the trace byte for byte. *)\n'
        'From Coq Require Import String List.\nImport ListNotations.\nOpen Scope string_scope.\n'
        'Definition raw_parameters : string := ' + coq_string(params) + '.\n'
        'Definition raw_sections : list (string * string * option string) := [\n' +
        ';\n'.join(' (' + coq_string(n) + ', ' + coq_string(p) + ', ' + opt(r) + ')' for n, p, r in secs)
        + '].\n')


if __name__ == '__main__':
    main(*sys.argv[1:])
