"""Package exact byte excerpts of pinned port primitive definitions (E2E-17).

Byte packaging only: it locates each named top-level definition in a pinned,
blob-checked source file, copies its exact bytes into a Coq string literal and
records the byte span. Reading, decoding and admission are Rocq computations
(rocq/SchemeWrappers.v, rocq/CLWrappers.v); this script decides nothing.
"""
from pathlib import Path
import hashlib
import sys

SOURCES = {
    'scheme_primitives': ('ports/upstream/primitives.scm', '92b8875a276848b473c59879f075f429ba44a7a0'),
    'scheme_prelude': ('ports/upstream/chez-prelude.scm', '18d1ce9a8dc7073ec2be69fd9c53b9fb70d77ef3'),
    'cl_primitives': ('ports/upstream/shen-cl/primitives.lsp', 'f9b11c8a0b57c8492e66094d5e236a8711983e7a'),
}
# (profile, source key, opening text of the definition)
EXCERPTS = [
    ('scheme', 'scheme_prelude', '(define-syntax raise-error\n'),
    ('scheme', 'scheme_primitives', '(define (kl:_scm.assert-boolean value)\n'),
    ('scheme', 'scheme_primitives', '(define (vector=? a b)\n'),
    ('scheme', 'scheme_primitives', '(define (kl:= a b)\n'),
    ('cl', 'cl_primitives', '(defun |cons?| (X)\n'),
    ('cl', 'cl_primitives', '(defun |string?| (s)\n'),
    ('cl', 'cl_primitives', '(defun |number?| (n)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.equal?| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.absequal| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.numeric-equal| (x y)\n'),
    ('cl', 'cl_primitives', '(defun cf-vectors (x y lx ly)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.double-precision| (x)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.multiply| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.add| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.subtract| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.divide| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.greater?| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.less?| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.greater-than-or-equal-to?| (x y)\n'),
    ('cl', 'cl_primitives', '(defun |shen-cl.less-than-or-equal-to?| (x y)\n'),
]


def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


def form_end(text, start):
    """End of the parenthesised form opening at start (strings and ; comments skipped)."""
    depth, i, in_string = 0, start, False
    while i < len(text):
        c = text[i]
        if in_string:
            if c == '\\':
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
        elif c == ';':
            i = text.index('\n', i)
            continue
        elif c == '|':
            i = text.index('|', i + 1)
        elif c == '#' and text[i + 1] == '\\':
            i += 2
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise SystemExit('Unterminated definition')


def excerpts():
    data = {}
    for key, (path, expected) in SOURCES.items():
        raw = Path(path).read_bytes()
        if blob(raw) != expected:
            raise SystemExit('Pinned source blob mismatch: ' + path)
        if any(b >= 128 for b in raw):
            raise SystemExit('Non-ASCII pinned source: ' + path)
        data[key] = raw.decode()
    out = []
    for profile, key, opening in EXCERPTS:
        text = data[key]
        if text.count(opening) != 1:
            raise SystemExit('Definition not unique: ' + opening.strip())
        start = text.index(opening)
        end = form_end(text, start)
        out.append((profile, key, SOURCES[key][0], SOURCES[key][1], start, end, text[start:end]))
    return out


def render():
    lines = ['(* Generated by scripts/package-primitives.py from pinned, blob-checked',
             '   sources. Exact definition bytes only; nothing here is decoded. *)',
             'From Coq Require Import String List.',
             'Import ListNotations.',
             'Open Scope string_scope.']
    for profile in ('scheme', 'cl'):
        chosen = [e for e in excerpts() if e[0] == profile]
        lines.append('Definition %s_spans : list (string * string * nat * nat) := [' % profile)
        lines.append(';\n'.join('  ("%s", "%s", %d, %d)' % (path, b, s, e) for _, _, path, b, s, e, _ in chosen) + '].')
        body = '\n\n'.join(t for *_, t in chosen).replace('"', '""')
        lines.append('Definition %s_source : string := "%s\n".' % (profile, body))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    Path(sys.argv[1]).write_text(render())
