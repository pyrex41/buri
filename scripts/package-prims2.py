"""Byte packaging for the Wave-D primitives lane (E2E-17, prims2).

Packaging only, never acceptance: it checks the pinned blob of each source
file, locates each named top-level definition, copies its exact bytes into
a Coq string literal and records the byte span. Reading, decoding, admission
and every theorem are Rocq computations (rocq/SchemeIntern.v,
rocq/CLStrings.v); this script decides nothing.

  python3 scripts/package-prims2.py PATCHED_OUT DEST.v

PATCHED_OUT is the directory written by `package-patched.py apply`; the
patched Shen-Scheme primitives.scm is read from it and its blob is checked.
"""
from pathlib import Path
import hashlib
import importlib.util
import sys

spec = importlib.util.spec_from_file_location('pp', 'scripts/package-primitives.py')
pp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pp)

# (Coq name, source path or patched-relative path, pinned blob, opening text)
STOCK_SCM = ('ports/upstream/primitives.scm', '92b8875a276848b473c59879f075f429ba44a7a0')
PATCHED_SCM = ('shen-scheme/primitives.scm', '526a89b2d7693e11f50b4726efbd2ed8f111d1fe')
CL = ('ports/upstream/shen-cl/primitives.lsp', 'f9b11c8a0b57c8492e66094d5e236a8711983e7a')
EXCERPTS = [
    ('stock_intern', 'stock', '(define (kl:intern name)\n'),
    ('patched_intern', 'patched', '(define (kl:intern name)\n'),
    ('cl_intern', 'cl', '(defun |intern| (String)\n'),
    ('cl_pos', 'cl', '(defun |pos| (x n)\n'),
    ('cl_tlstr', 'cl', '(defun |tlstr| (x)\n'),
    ('cl_n_to_string', 'cl', '(defun |n->string| (n)\n'),
    ('cl_string_to_n', 'cl', '(defun |string->n| (s)\n'),
    ('cl_get_address', 'cl', '(defun |<-address| (vector n)\n'),
]


def load(path, expected):
    raw = Path(path).read_bytes()
    if pp.blob(raw) != expected:
        raise SystemExit('Pinned blob mismatch: ' + str(path))
    if any(b >= 128 for b in raw):
        raise SystemExit('Non-ASCII pinned source: ' + str(path))
    return raw.decode()


def render(patched_out):
    texts = {
        'stock': (STOCK_SCM[0], STOCK_SCM[1], load(*STOCK_SCM)),
        'patched': ('patched:' + PATCHED_SCM[0], PATCHED_SCM[1],
                    load(Path(patched_out) / PATCHED_SCM[0], PATCHED_SCM[1])),
        'cl': (CL[0], CL[1], load(*CL)),
    }
    lines = ['(* Generated by scripts/package-prims2.py from pinned, blob-checked',
             '   sources (the patched Shen-Scheme primitives.scm is upstream blob',
             '   92b8875a with ports/patches/shen-scheme-primitives.diff applied).',
             '   Exact definition bytes only; nothing here is decoded. *)',
             'From Coq Require Import String.',
             'Open Scope string_scope.']
    for name, key, opening in EXCERPTS:
        path, b, text = texts[key]
        if text.count(opening) != 1:
            raise SystemExit('Definition not unique: ' + opening.strip())
        start = text.index(opening)
        end = pp.form_end(text, start)
        lines.append('Definition %s_span : string * string * nat * nat := ("%s", "%s", %d, %d).'
                     % (name, path, b, start, end))
        lines.append('Definition %s_source : string := "%s\n".' % (name, text[start:end].replace('"', '""')))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    Path(sys.argv[2]).write_text(render(sys.argv[1]))
