"""Embed exact captured bytes. Rocq alone decodes and validates KLambda."""
from pathlib import Path
import sys

source, destination = map(Path, sys.argv[1:])
bits = source.read_bytes()
if not bits or any(b not in b'01' for b in bits):
    raise SystemExit('Capture must contain only ASCII 0 and 1 bytes')
preamble = '''(* Exact registered-KLambda capture. Generated by package-frontend.py. *)
From Coq Require Import List String.
From Buri Require Import Wire Encoder EncoderSource EncoderNames EncoderFrontend.
Import ListNotations.
Open Scope string_scope.
Import Encoder.Encoder EncoderNames.EncoderNames EncoderFrontend.EncoderFrontend.
Definition encoder_kl_text : string := "'''
proofs = '''".
Definition encoder_kl_ok := accepted 150 encoder_kl_text.
Theorem encoder_kl_checked : encoder_kl_ok = true.
Proof. vm_compute. reflexivity. Qed.
Global Opaque encoder_kl_text.
Theorem encoder_kl_sound : exists raw prog,
 check_capture 150 encoder_kl_text = Some (raw,prog) /\\
 Wire.capture raw = encoder_kl_text /\\ program_resolves prog.
Proof. exact (accepted_sound 150 encoder_kl_text encoder_kl_checked). Qed.
Theorem encoder_kl_execution :
 encoder_source_text = Encoder.source /\\
 exists raw prog, check_capture 150 encoder_kl_text = Some (raw,prog) /\\
 capture_coverage 150 raw prog /\\
 (forall f x y n, EncoderNames.eval n prog (arguments (parameters (prog f)) x y) (expression (prog f)) =
    Encoder.eval n [x;y] (body f)) /\\
 (forall d, exists n, EncoderNames.eval n prog (arguments (parameters (prog Datum)) (Data d) (Number 0))
    (expression (prog Datum)) = Returned (Text (Wire.capture d))) /\\
 (forall d n v, EncoderNames.eval n prog (arguments (parameters (prog Datum)) (Data d) (Number 0))
    (expression (prog Datum)) = Returned v -> v = Text (Wire.capture d)).
Proof. split; [exact encoder_source_exact | exact (accepted_execution 150 encoder_kl_text encoder_kl_checked)]. Qed.
'''
destination.write_text(preamble + bits.decode('ascii') + proofs)
