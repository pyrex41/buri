"""Package exact ASCII source bytes. No source parsing or proof decisions."""
from pathlib import Path
import sys

raw = Path(sys.argv[1]).read_bytes()
assert all(b < 128 for b in raw), 'Encoder source must be ASCII'
source = raw.decode('ascii').replace('"', '""')
Path(sys.argv[2]).write_text('''(* Exact loaded Shen source; generated by scripts/package-encoder.py. *)
From Coq Require Import List String.
Import ListNotations.
From Buri Require Import Wire Encoder.
Open Scope string_scope.
Definition encoder_source_text : string := "''' + source + '''".
Theorem encoder_source_exact : encoder_source_text = Encoder.source.
Proof. vm_compute. reflexivity. Qed.
Theorem source_linked_encoder :
 encoder_source_text = Encoder.source /\\
 forall d, Encoder.evaluates [Encoder.Data d;Encoder.Number 0]
   (Encoder.body Encoder.Datum) (Encoder.Text (Wire.capture d)).
Proof. split; [exact encoder_source_exact | exact Encoder.datum_correct]. Qed.
Theorem source_linked_roundtrip :
 encoder_source_text = Encoder.source /\\
 forall d out, Encoder.evaluates [Encoder.Data d;Encoder.Number 0]
   (Encoder.body Encoder.Datum) (Encoder.Text out) -> Wire.decode_text out = Some d.
Proof. split; [exact encoder_source_exact | exact Encoder.encoder_decodes]. Qed.
''')
