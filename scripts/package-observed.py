"""Literal bit packaging only; Rocq decodes and validates all paired bodies."""
from pathlib import Path
import sys
source, destination = map(Path, sys.argv[1:])
bits = source.read_bytes()
if not bits or any(b not in b'01' for b in bits):
    raise SystemExit('Capture must contain only ASCII 0 and 1 bytes')
destination.write_text('''(* Exact observed compilation capture. Generated by package-observed.py. *)
From Coq Require Import List String.
From Buri Require Import Wire Encoder EncoderSource EncoderNames EncoderScheme ObservedEncoder.
Import ListNotations.
Open Scope string_scope.
Import Encoder.Encoder EncoderNames.EncoderNames ObservedEncoder.ObservedEncoder.
Definition observed_encoder_text : string := "''' + bits.decode('ascii') + '''".
Theorem observed_encoder_checked : accepted 250 observed_encoder_text = true.
Proof. vm_compute. reflexivity. Qed.
Global Opaque observed_encoder_text.
Theorem observed_encoder_execution :
 encoder_source_text = Encoder.source /\\
 exists raw root sp tp,
 check_capture 250 observed_encoder_text = Some (raw,root,sp,tp) /\\
 Wire.capture raw = observed_encoder_text /\\ coverage 250 root sp tp /\\
 program_resolves sp /\\ target_resolves tp /\\
 (forall f x y n v, EncoderNames.eval n sp (arguments (parameters (sp f)) x y) (expression (sp f)) = Returned v ->
   EncoderScheme.exec (resolved_table tp) [x;y] (resolved_table tp f) v) /\\
 (forall d, EncoderScheme.exec (resolved_table tp) [Data d;Number 0]
   (resolved_table tp Datum) (Text (Wire.capture d))) /\\
 (forall d v, EncoderScheme.exec (resolved_table tp) [Data d;Number 0]
   (resolved_table tp Datum) v -> v = Text (Wire.capture d)).
Proof.
 split; [exact encoder_source_exact |].
 destruct (accepted_sound _ _ observed_encoder_checked) as [raw [root [sp [tp [C [W [V [S T]]]]]]]].
 exists raw,root,sp,tp. split; [exact C |]. split; [exact W |].
 split; [exact V |]. split; [exact S |]. split; [exact T |].
 split; [eapply paired_execution; eauto |].
 split; intros d; apply (checked_execution tp T d).
Qed.
''')
