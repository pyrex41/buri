#!/usr/bin/env python3
"""Turn one stage 0 file pair (<name>.forms, <name>.sbc) into Rocq data, for JitLowerStage0.v.

Trusted, and only a reader: it tokenizes the files' syntax (src/lowerer/README.md, "Output syntax")
into the generic tree `sx` of rocq/JitLowerStage0.v. It does not decide what a symbol, list or
instruction means; Rocq turns the trees into KLambda values and code objects and runs the checker.
Its one numeric step is decoding a real literal to IEEE-754 bits (struct), named in the ledger as
OB-JIT-LOWER-READER.

    stage0_to_rocq.py STAGE0_DIR NAME OUT.v
    stage0_to_rocq.py --norm STAGE0_DIR NORM_DIR NAME OUT.v

The second form also reads NORM_DIR/<name>.norm, lower.shen's normal form of each definition (one
entry per definition, in .forms order), into a third list of the same trees, for
rocq/JitNormStage0.v. It tokenizes that file exactly as the others and decides nothing about it.

    stage0_to_rocq.py --D STAGE0_DIR NORM_DIR OUT.v NAME...

The third form (D00) reads <name>.forms, NORM_DIR/<name>.norm and <name>.sbc for each NAME, in the
order given, and writes the three lists concatenated, for rocq/JitFrontD.v: Rocq decodes the rows,
builds each definition's store D (JitFrontD.D_of) and decides D_compiled'. Which names a D holds is
decided in Rocq, never here; this mode only tokenizes, as the others do.

    stage0_to_rocq.py --prolog STAGE0_DIR OUT.v NAME...

The fourth form (r1-f-prolog) reads <name>.forms for each NAME and writes them for
rocq/JitFrontProlog.v, whose prolog_scan counts the Prolog rewrites' source shapes in Rocq.
"""
import struct, sys

def tokens(text):
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in ' \n\t\r':
            i += 1
        elif c in '()':
            yield c; i += 1
        elif c == '"':
            j, out = i + 1, []
            while text[j] != '"':
                if text[j] == '\\':
                    k = text[j + 1]
                    if k == 'x':
                        out.append(int(text[j + 2:j + 4], 16)); j += 4
                    else:
                        out.append(ord(k)); j += 2
                else:
                    out.append(ord(text[j])); j += 1
            yield ('str', out); i = j + 1
        else:
            j = i
            while j < n and text[j] not in ' \n\t\r()"':
                j += 1
            yield ('atom', text[i:j]); i = j

def parse(toks):
    stack = [[]]
    for t in toks:
        if t == '(':
            stack.append([])
        elif t == ')':
            x = stack.pop(); stack[-1].append(('list', x))
        else:
            stack[-1].append(t)
    assert len(stack) == 1
    return stack[0]

def is_number(a):
    return a[0].isdigit() or (len(a) > 1 and a[0] in '+-.' and (a[1].isdigit() or a[1] == '.'))

def rocq(x):
    if x[0] == 'list':
        return '(XList [' + ';'.join(rocq(y) for y in x[1]) + '])'
    if x[0] == 'str':
        return '(XStr [' + ';'.join('%d%%N' % b for b in x[1]) + '])'
    a = x[1]
    if is_number(a):
        if any(ch in a for ch in '.eE'):
            bits = struct.unpack('<Q', struct.pack('<d', float(a)))[0]
            return '(XReal %d)' % bits
        return '(XInt (%d))' % int(a)
    assert '"' not in a and '\\' not in a, a
    return '(XSym "%s")' % a

def main(d, name, out):
    forms = parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    sbc = parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    ident = name.replace('-', '_')
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py from %s.forms and %s.sbc. *)\n' % (name, name))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitLowerStage0.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0.\nOpen Scope string_scope.\n')
        f.write('Definition forms_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in forms)))
        f.write('Definition sbc_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in sbc)))
        f.write('Definition result_%s := Eval vm_compute in tally forms_%s sbc_%s.\n' % (ident, ident, ident))
        f.write('Print result_%s.\n' % ident)

def main_norm(d, nd, name, out):
    forms = parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    norm = parse(tokens(open('%s/%s.norm' % (nd, name)).read()))
    sbc = parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    ident = name.replace('-', '_')
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py --norm from %s.forms, %s.norm and %s.sbc. *)\n' % (name, name, name))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitLowerStage0 JitNormStage0.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0 JitNormStage0.JitNormStage0.\nOpen Scope string_scope.\n')
        f.write('Definition forms_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in forms)))
        f.write('Definition norm_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in norm)))
        f.write('Definition sbc_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in sbc)))
        f.write('Definition nresult_%s := Eval vm_compute in tally_norm forms_%s norm_%s sbc_%s.\n' % (ident, ident, ident, ident))
        f.write('Print nresult_%s.\n' % ident)

def main_D(d, nd, out, names):
    fs, ns, ss = [], [], []
    for name in names:
        fs += parse(tokens(open('%s/%s.forms' % (d, name)).read()))
        ns += parse(tokens(open('%s/%s.norm' % (nd, name)).read()))
        ss += parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py --D from the .forms, .norm and .sbc of: %s. *)\n' % ' '.join(names))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitLowerStage0 JitFrontD.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0.\nOpen Scope string_scope.\n')
        f.write('Definition dforms : list sx := [%s].\n' % ';\n '.join(rocq(x) for x in fs))
        f.write('Definition dnorm : list sx := [%s].\n' % ';\n '.join(rocq(x) for x in ns))
        f.write('Definition dsbc : list sx := [%s].\n' % ';\n '.join(rocq(x) for x in ss))
        f.write('Definition dstats := Eval vm_compute in JitFrontD.JitFrontD.D_stats dforms dnorm dsbc.\n')
        f.write('Print dstats.\n')

def main_prolog(d, out, names):
    """r1-f-prolog: the .forms of every NAME, for JitFrontProlog.prolog_scan (tokenizer only)."""
    fs = []
    for name in names:
        fs += parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py --prolog from the .forms of: %s. *)\n' % ' '.join(names))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitLowerStage0 JitFrontProlog.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0.\nOpen Scope string_scope.\n')
        f.write('Definition pforms : list sx := [%s].\n' % ';\n '.join(rocq(x) for x in fs))
        f.write('Definition pscan := Eval vm_compute in JitFrontProlog.JitFrontProlog.prolog_scan pforms.\n')
        f.write('Print pscan.\n')

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == '--prolog':
    import threading
    sys.setrecursionlimit(200000)
    threading.stack_size(1 << 29)
    failed = []
    def run_prolog():
        try:
            main_prolog(sys.argv[2], sys.argv[3], sys.argv[4:])
        except BaseException as e:
            failed.append(e); raise
    th = threading.Thread(target=run_prolog); th.start(); th.join()
    sys.exit(1 if failed else 0)

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == '--D':
    # As for --norm: witness trees nest deeply, so a larger stack and recursion limit (resource only).
    import threading
    sys.setrecursionlimit(200000)
    threading.stack_size(1 << 29)
    failed = []
    def run_D():
        try:
            main_D(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:])
        except BaseException as e:
            failed.append(e); raise
    th = threading.Thread(target=run_D); th.start(); th.join()
    sys.exit(1 if failed else 0)

if __name__ == '__main__':
    if sys.argv[1] == '--norm':
        # Witness trees nest deeper than Python's default recursion limit (init.norm): a resource
        # limit only, raised on a thread with a larger stack.
        import threading
        sys.setrecursionlimit(200000)
        threading.stack_size(1 << 29)
        failed = []
        def run():
            try:
                main_norm(*sys.argv[2:6])
            except BaseException as e:
                failed.append(e); raise
        th = threading.Thread(target=run); th.start(); th.join()
        if failed:
            sys.exit(1)
    else:
        main(*sys.argv[1:4])
