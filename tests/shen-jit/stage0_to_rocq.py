IMAGE_FILES = ["toplevel", "core", "sys", "dict", "sequent", "yacc", "reader", "prolog", "track", "load",
    "writer", "macros", "declarations", "types", "t-star", "init", "shen-jit", "lower",
    "extension-features", "extension-launcher", "extension-programmable-pattern-matching",
    "extension-namespaces", "extension-expand-dynamic", "extension-type-annotations"]

def main_image(exe, out):
    """r21-image-lane: the image of EXE as 32-bit halves, and the driver for JitImage (reader only)."""
    b = open(exe, 'rb').read()
    assert len(b) >= 16 and b[-8:] == b'SJHI-END'
    n = struct.unpack('<Q', b[-16:-8])[0]
    assert n % 8 == 0 and 16 <= n <= len(b)
    ws = struct.unpack('<%dQ' % (n // 8), b[len(b) - n:])
    ids = [fl.replace('-', '_') for fl in IMAGE_FILES]
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py --image from %s (%d image bytes at offset %d). *)\n' % (exe, n, len(b) - n))
        f.write('From Coq Require Import List ZArith NArith String Uint63.\nFrom Buri Require Import JitBytecode JitLowerStage0 JitImage.\n')
        f.write('From Buri.s0 Require %s.\n' % ' '.join('S0_%s' % i for i in ids))
        f.write('Import ListNotations.\nOpen Scope string_scope.\nModule I := JitImage.JitImage.\n')
        names = []
        for i in range(0, len(ws), 1000):
            nm = 'h%d' % (i // 1000); names.append(nm)
            f.write('Definition %s : list int := [%s].\n' % (nm, ';'.join('%d%%uint63;%d%%uint63' % (w >> 32, w & 0xffffffff) for w in ws[i:i + 1000])))
        f.write('Definition halves : list int := %s.\n' % ' ++ '.join(names))
        # Rocq joins the halves (JitImage.words_of_halves); the join uses Rocq's primitive 63-bit integers,
        # which Print Assumptions lists. N literals for the words instead took more than 140 s to elaborate.
        f.write('Definition words : list N := I.words_of_halves halves.\n')
        f.write('Definition sbc_files := [%s].\n' % ';\n '.join('("%s", S0_%s.sbc_%s)' % (fl, i, i) for fl, i in zip(IMAGE_FILES, ids)))
        f.write('Definition fs := I.files_val sbc_files.\n')
        f.write('Definition defs := flat_map snd fs.\n')
        f.write('Lemma image_files : map fst sbc_files = I.stage1_files.\nProof. vm_compute. reflexivity. Qed.\n')
        f.write('Lemma image_code_ok : I.code_check words fs = true.\nProof. vm_compute. reflexivity. Qed.\n')
        f.write('Print Assumptions image_code_ok.\n')
        f.write('Definition g_print := JitBytecode.JitBytecode.sym "print".\n')
        f.write('Lemma image_mutants_caught :\n'
                '  (I.mut_caught (I.mut_arity words g_print) (List.length words) defs g_print &&\n'
                '   I.mut_caught (I.mut_byte words g_print) (List.length words) defs g_print)%bool = true.\n'
                'Proof. vm_compute. reflexivity. Qed.\n'
                'Print Assumptions image_mutants_caught.\n')
        f.write('Definition image_facts := Eval vm_compute in\n'
                ' match I.image_of words with\n'
                ' | Some (_, c) => Some (List.length words, List.length defs, I.census_of c defs, I.sealed_by_file c fs,\n'
                '     map (fun s => (s, I.name_facts c defs (JitBytecode.JitBytecode.sym s)))\n'
                '       ["thaw"; "hd"; "tl"; "thread"; "shen.x.launcher.execute-all"; "shen.x.launcher.main"])\n'
                ' | None => None end.\n')
        f.write('Print image_facts.\n')

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == '--image':
    main_image(sys.argv[2], sys.argv[3])
    sys.exit(0)

if __name__ == '__main__':
    if sys.argv[1] == '--norm':
        # Witness trees nest deeper than Python's default recursion limit (init.norm): a resource
        # limit only, raised on a thread with a larger stack.
        import threading
        sys.setrecursionlimit(200000)
        threading.stack_size(1 << 29)
        failed = []
        def run():
            try:
                main_norm(*sys.argv[2:6])
            except BaseException as e:
                failed.append(e); raise
        th = threading.Thread(target=run); th.start(); th.join()
        if failed:
            sys.exit(1)
    else:
        main(*sys.argv[1:4])
