#!/usr/bin/env python3
"""Turn one stage 0 file pair (<name>.forms, <name>.sbc) into Rocq data, for JitLowerStage0.v.

Trusted, and only a reader: it tokenizes the files' syntax (src/lowerer/README.md, "Output syntax")
into the generic tree `sx` of rocq/JitLowerStage0.v. It does not decide what a symbol, list or
instruction means; Rocq turns the trees into KLambda values and code objects and runs the checker.
Its one numeric step is decoding a real literal to IEEE-754 bits (struct), named in the ledger as
OB-JIT-LOWER-READER.

    stage0_to_rocq.py STAGE0_DIR NAME OUT.v
"""
import struct, sys

def tokens(text):
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in ' \n\t\r':
            i += 1
        elif c in '()':
            yield c; i += 1
        elif c == '"':
            j, out = i + 1, []
            while text[j] != '"':
                if text[j] == '\\':
                    k = text[j + 1]
                    if k == 'x':
                        out.append(int(text[j + 2:j + 4], 16)); j += 4
                    else:
                        out.append(ord(k)); j += 2
                else:
                    out.append(ord(text[j])); j += 1
            yield ('str', out); i = j + 1
        else:
            j = i
            while j < n and text[j] not in ' \n\t\r()"':
                j += 1
            yield ('atom', text[i:j]); i = j

def parse(toks):
    stack = [[]]
    for t in toks:
        if t == '(':
            stack.append([])
        elif t == ')':
            x = stack.pop(); stack[-1].append(('list', x))
        else:
            stack[-1].append(t)
    assert len(stack) == 1
    return stack[0]

def is_number(a):
    return a[0].isdigit() or (len(a) > 1 and a[0] in '+-.' and (a[1].isdigit() or a[1] == '.'))

def rocq(x):
    if x[0] == 'list':
        return '(XList [' + ';'.join(rocq(y) for y in x[1]) + '])'
    if x[0] == 'str':
        return '(XStr [' + ';'.join('%d%%N' % b for b in x[1]) + '])'
    a = x[1]
    if is_number(a):
        if any(ch in a for ch in '.eE'):
            bits = struct.unpack('<Q', struct.pack('<d', float(a)))[0]
            return '(XReal %d)' % bits
        return '(XInt (%d))' % int(a)
    assert '"' not in a and '\\' not in a, a
    return '(XSym "%s")' % a

def main(d, name, out):
    forms = parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    sbc = parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    ident = name.replace('-', '_')
    with open(out, 'w') as f:
        f.write('(* Generated by tests/shen-jit/stage0_to_rocq.py from %s.forms and %s.sbc. *)\n' % (name, name))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitLowerStage0.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0.\nOpen Scope string_scope.\n')
        f.write('Definition forms_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in forms)))
        f.write('Definition sbc_%s : list sx := [%s].\n' % (ident, ';\n '.join(rocq(x) for x in sbc)))
        f.write('Definition result_%s := Eval vm_compute in tally forms_%s sbc_%s.\n' % (ident, ident, ident))
        f.write('Print result_%s.\n' % ident)

if __name__ == '__main__':
    main(*sys.argv[1:4])
