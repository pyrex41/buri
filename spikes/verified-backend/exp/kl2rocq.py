#!/usr/bin/env python3
"""Spike 10: emit a Rocq file that runs KLambda definitions on Búri's own small-step semantics
(rocq/KLSemantics.v `next`), for the CertiRocq route. The forms become KLValue data and are turned
into syntax by KLSemantics.parse inside Rocq, as eval-kl does; this script only tokenizes.

    kl2rocq.py N OUT.v DEFS.kl ...      (runs (vb.bench N 0))
"""
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from kl2cml import parse

def val(e):
    if isinstance(e, tuple): return "(VStr (of_string (\"%s\")))" % e[1].replace("\"", "\"\"").replace("\n", "\" ++ nl ++ \"")
    if isinstance(e, list):
        out = 'VNil'
        for x in reversed(e): out = '(VCons %s %s)' % (val(x), out)
        return out
    if e.lstrip('-').isdigit(): return '(VNum (NInt (%s)%%Z))' % e
    if e in ('true', 'false'): return '(VBool %s)' % e
    return '(VSym (of_string "%s"))' % e

def main():
    n, out, files = sys.argv[1], sys.argv[2], sys.argv[3:]
    forms = []
    for p in files: forms += parse(open(p).read())
    defs = '\n  ; '.join(val(f) for f in forms)
    open(out, 'w').write(f'''(* Generated by spikes/verified-backend/exp/kl2rocq.py. *)
From Coq Require Import List ZArith NArith String Ascii Bool.
From Buri Require Import Observation KLSyntax KLValue KLSemantics.
Import ListNotations.
Import Observation.Observation KLSyntax.KLSyntax KLValue.KLValue KLSemantics.KLSemantics.
Open Scope string_scope.
Definition nl : string := String (ascii_of_nat 10) EmptyString.

(* A concrete profile: no inexact numbers, no limits. *)
Definition vb_profile : profile := Profile
  (fun _ _ _ => None) (fun _ _ _ => false) (fun _ _ => NInt 0) (fun _ => []) (fun _ => None)
  (fun _ => []) VNil (fun _ _ => None) None None.

Definition prims : list prim := [PCons; PHd; PTl; PConsP; PEqual; PSimpleError;
  PAdd; PSub; PMul; PGt; PLt; PGe; PLe; PNumberP].
Definition forms : list value :=
  [ {defs} ].
Fixpoint load (fs : list value) (acc : list (name * fundef)) : list (name * fundef) :=
  match fs with
  | [] => acc
  | v :: fs => match parse [] v with
               | Some (EDefun f ps b) => load fs ((f, FUser ps b) :: acc)
               | _ => load fs acc end end.
Definition store0 : store :=
  Store [] [] (load forms (map (fun p => (of_string (prim_name p), FPrim p)) prims)).

Definition one (c : config) : config + option kl_outcome :=
  match next vb_profile c with MTau c' => inl c' | MFinal o => inr (Some o) | _ => inr None end.
Definition bind (r : config + option kl_outcome) (k : config -> config + option kl_outcome) :=
  match r with inl c => k c | inr o => inr o end.
(* Fuel 2^|p| steps, without a unary nat. *)
Fixpoint drive (p : positive) (c : config) : config + option kl_outcome :=
  match p with
  | xH => one c
  | xO q => bind (drive q c) (drive q)
  | xI q => bind (one c) (fun c => bind (drive q c) (drive q)) end.

Definition start : config :=
  Cfg (Eval [] (ECall (of_string "vb.bench") [ENum (NInt {n}%Z); ENum (NInt 0%Z)])) [] store0.
Definition result : Z :=
  match drive (2 ^ 40)%positive start with
  | inr (Some (Normal (VNum (NInt z)))) => z
  | inr (Some _) => (-1)%Z
  | inr None => (-2)%Z
  | inl _ => (-3)%Z end.
''')

if __name__ == '__main__': main()
