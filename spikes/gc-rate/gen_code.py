#!/usr/bin/env python3
"""Fetch and decode facts for chosen address ranges of the runtime image, including RVC
instructions (Theorem's gen_fd_lemmas walks 4 bytes at a time, so it can't do this).
Every lemma is closed by a VM-checked cast, so a wrong fact fails to compile.
Usage: gen_code.py ELF LO:HI[,LO:HI...] OUT"""
import struct,sys
sys.path.insert(0,'/work-s5/tools')
import gen_fd_lemmas as g
elf,ranges,out=sys.argv[1:4]
b=open(elf,'rb').read()
base=0x10000
insns=[]
for r in ranges.split(','):
    lo,hi=[int(x,16) for x in r.split(':')]
    pc=lo
    while pc<hi:
        w=struct.unpack_from('<I',b,pc-base)[0]
        insns.append((pc,w))
        pc+= 4 if w&3==3 else 2
dec=g.decode_words(sorted({w for _,w in insns}),['-Q','/work-s5/_build/default/theories/Riscv','LinuxProcessSemantics.Riscv'])
L=['(** AUTO-GENERATED by spikes/gc-rate/gen_code.py. Proof-side: a wrong fact fails to compile. *)',
'From Stdlib Require Import NArith ZArith List.',
'From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase RiscvSemantics MemImageType.',
'From LinuxProcessSemantics.Examples.gc_rate_ns Require Import SourceMemImage.',
'From LinuxProcessSemantics.Riscv Require Import Prelude Instr Decode DecodeC.',
'From LinuxProcessSemantics.Common Require Import PropExec StepTac.',
'Import ListNotations.','Open Scope bv_scope.',
'Definition source_segs := SourceMemImage_loaded_segments.',
'Definition source_phdrs := SourceMemImage_phdrs.',
'Global Strategy 200 [source_segs].','Ltac vm_refl := vm_refl_bv.','']
for pc,w in insns:
    assert dec[w]!='None',hex(pc)
    a=f'{pc:x}'
    L.append(f'Lemma SF_{a} : fetch_word_wx source_segs 0x{a} = Some {w}. Proof. vm_refl. Qed.')
    L.append(f'Lemma SD_{a} : decode_any (Z_to_bv 32 {w}) = {dec[w]}. Proof. vm_refl. Qed.')
L.append("Definition ro4 (a v : word) : Prop := exists bs, rdn_none a = Some bs /\\ bytes_le_to_Z bs = bv_unsigned v.".replace('rdn_none a','PropExec.rdn source_segs (fun _ => None) a 4%nat'))
for name,jt in (('JTow',0x45e50),('JTcv',0x43ae8)):
    for i in range(11):
        a=jt+4*i; bs=b[a-base:a-base+4]; v=struct.unpack('<I',bs)[0]
        lits='; '.join(f'Z_to_bv 8 {x}' for x in bs)
        L.append(f'Lemma {name}_{i+1} : ro4 (Z_to_bv 64 {a}) (Z_to_bv 64 {v}). Proof. exists [{lits}]. split; vm_refl. Qed.')
open(out,'w').write('\n'.join(L)+'\n')
print(len(insns),'instructions')
