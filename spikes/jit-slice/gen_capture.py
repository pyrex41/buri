#!/usr/bin/env python3
"""Generates coq/SliceCode.v from the emitter's dump, so the proof is about exactly those bytes.
usage: gen_capture.py native.bin BASE_HEX out.v"""
import hashlib, sys
data = open(sys.argv[1], 'rb').read()
base = int(sys.argv[2], 16)
digest = hashlib.sha256(data).hexdigest()
rows = [' ; '.join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
body = ' ;\n     '.join(rows)
open(sys.argv[3], 'w').write(f"""(** Generated by gen_capture.py from the emitter's output.  Do not edit.
    sha256 {digest} *)
From Stdlib Require Import ZArith List.
Import ListNotations.
Definition code_base : Z := {base}%Z.
Definition code_len : Z := {len(data)}%Z.
Definition captured : list Z :=
  [ {body} ]%Z.
""")
print('sha256', digest, 'bytes', len(data), 'base', hex(base))
