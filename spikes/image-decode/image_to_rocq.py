#!/usr/bin/env python3
"""Spike reader (OB-JIT-IMAGE-READER), not in the lane. image_to_rocq.py EXE STAGE0_DIR OUT.v: the last heap image of EXE as little-endian 64-bit words,
and the 24 stage 0 .sbc files (stage 1's order) as sx trees, for rocq/JitImage.v. A reader only:
it finds the image from the trailer's length (as image_load does) and splits bytes into words."""
import struct, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tests', 'shen-jit'))
from stage0_to_rocq import tokens, parse, rocq
FILES = ["toplevel", "core", "sys", "dict", "sequent", "yacc", "reader", "prolog", "track", "load",
    "writer", "macros", "declarations", "types", "t-star", "init", "shen-jit", "lower",
    "extension-features", "extension-launcher", "extension-programmable-pattern-matching",
    "extension-namespaces", "extension-expand-dynamic", "extension-type-annotations"]
def main(exe, d, out):
    b = open(exe, 'rb').read()
    n = struct.unpack('<Q', b[-16:-8])[0]
    assert b[-8:] == b'SJHI-END' and n % 8 == 0 and n <= len(b)
    img = b[len(b) - n:]
    ws = struct.unpack('<%dQ' % (n // 8), img)
    with open(out, 'w') as f:
        f.write('(* Generated by image_to_rocq.py from %s (%d image bytes at offset %d) and %s. *)\n' % (exe, n, len(b) - n, d))
        f.write('From Coq Require Import List ZArith NArith String.\nFrom Buri Require Import JitBytecode JitLowerStage0 JitImage.\n')
        f.write('Import ListNotations JitLowerStage0.JitLowerStage0.\nOpen Scope string_scope.\nLocal Open Scope N_scope.\n')
        names = []
        for i in range(0, len(ws), 1000):
            nm = 'w%d' % (i // 1000); names.append(nm)
            f.write('Definition %s : list N := [%s].\n' % (nm, ';'.join(str(w) for w in ws[i:i + 1000])))
        f.write('Definition nwords : N := %d.\n' % len(ws))
        f.write('Definition words : list N := %s.\n' % ' ++ '.join(names))
        snames = []
        for fl in FILES:
            sbc = parse(tokens(open('%s/%s.sbc' % (d, fl)).read()))
            nm = 'sbc_' + fl.replace('-', '_'); snames.append(nm)
            f.write('Definition %s : list sx := [%s].\n' % (nm, ';\n '.join(rocq(x) for x in sbc)))
        f.write('Definition sbc_files : list (string * list sx) := [%s].\n' % ';'.join('("%s", %s)' % (fl, nm) for fl, nm in zip(FILES, snames)))
if __name__ == '__main__':
    main(*sys.argv[1:4])
