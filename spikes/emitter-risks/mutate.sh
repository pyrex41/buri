#!/bin/bash
# In buri-lps. Each mutant must fail to build; then the unmodified spike must build again.
# A rejected mutant only shows that this proof script, or the checker, fails on it.
here=$(cd "$(dirname "$0")" && pwd); export W=/work-s8m
D=$here/capture/data/shen.invoke.dump
run() { # name, setup command run in a temp copy of the spike
  m=$(mktemp -d); cp -a "$here"/. "$m"/
  ( cd "$m" && eval "$2" ) || { echo "MUTANT_NOT_APPLIED $1"; rm -rf "$m"; return; }
  if cmp -s "$m/coq/CfDefs.v" "$here/coq/CfDefs.v" && cmp -s "$m/coq/CfCaptured.v" "$here/coq/CfCaptured.v" \
     && cmp -s "$m/capture/data/shen.invoke.dump" "$D"; then echo "MUTANT_NOT_APPLIED $1"; rm -rf "$m"; return; fi
  out=$(LIMIT=600 bash "$m/dbuild.sh" theories/Examples/emitter_risks_ns/CfAudit.vo 2>&1)
  if echo "$out" | grep -q '^rc=0'; then echo "MUTANT_ACCEPTED $1"
  else echo "rejected $1: $(echo "$out" | grep -m1 -E 'Error' | cut -c1-110) [$(grep -m1 -oE 'Cf[A-Za-z]+\.v' /tmp/s8-work-s8m.log)]"; fi
  rm -rf "$m"
}
regen='python3 capture/gen_instance.py capture/data/shen.invoke.dump shen.invoke coq/CfCaptured.v >/dev/null'
pd() { echo "python3 patch_dump.py capture/data/shen.invoke.dump capture/data/shen.invoke.dump $* && $regen"; }
# The generated bytes
run b-tag-off-by-one "$(pd bytes 2a 00498513)"
run b-cons-field-order "$(pd bytes 26 0019b023)"
run b-room-too-small "$(pd bytes 10 01098593)"
run b-eq-branch-inverted "$(pd bytes 0c 04130863)"
run b-alloc-wrong-words "$(pd bytes 92 4589)"
run b-hp-not-reloaded "$(pd bytes a0 0004b903)"
run b-return-wrong-value "$(pd bytes 80 8526)"
run b-fp-not-published "$(pd bytes 88 ec80)"
run b-raise-check-wrong-status "$(pd bytes a4 4365)"
# The certificate from the emitter side
run c-cache-kept-at-alloc "$(pd state 9 2 14 0 0)"
run c-cut-shifted "$(pd cut 15 52)"
run c-slot-claimed-current "$(pd state 15 5 30 32 2)"
# The checker's own definition: a weaker check must break a proof
run s-no-hp-check "sed -i 's/same (yA y 8) (Lin KFp 0) \&\& same (yA y 9) (Lin KVm 0) \&\& same (yA y 19) (Lin KHp delta) \&\&/same (yA y 8) (Lin KFp 0) \&\& same (yA y 9) (Lin KVm 0) \&\&/' coq/CfDefs.v"
run s-no-room-zero-at-resume "sed -i 's/Z.eqb back (cut i) \&\& Z.eqb (sR s) 0 \&\& frame_kept s y \&\&/Z.eqb back (cut i) \&\& frame_kept s y \&\&/' coq/CfDefs.v"
run s-hd-without-pair "sed -i '/| IHd d x =>/{n;s/(Z.leb 0 x \&\& Z.ltb x 64 \&\& Z.testbit (sP s) x)%bool \&\&/true \&\&/}' coq/CfDefs.v"
run s-no-frame-kept-at-call "sed -i 's/same (yA y. 19) (Lin KHp 0) \&\& frame_kept s y. \&\&/same (yA y'\\'' 19) (Lin KHp 0) \&\&/' coq/CfDefs.v"
out=$(LIMIT=600 bash "$here/dbuild.sh" theories/Examples/emitter_risks_ns/CfAudit.vo 2>&1)
echo "$out" | grep -q '^rc=0' && echo restored-ok || { echo RESTORE_FAILED; echo "$out" | tail -5; }
