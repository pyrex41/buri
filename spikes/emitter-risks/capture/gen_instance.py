#!/usr/bin/env python3
"""Generates coq/CfCaptured.v from a checker dump: the exact bytes, bytecode words, cuts and states.
usage: gen_instance.py DUMP NAME OUT.v"""
import hashlib, sys
d = {}
for line in open(sys.argv[1]):
    k, _, v = line.strip().partition(' ')
    d[k] = v
name = sys.argv[2]
bytes_ = [int(x) for x in d['bytes'].split()]
words = [int(x) for x in d['words'].split()]
cuts = [int(x) for x in d['cuts'].split()]
consts = [tuple(int(y) for y in x.split(':')) for x in d['consts'].split()]
states = {}
for x in d['states'].split():
    w, C, M, P, R = x.split(':')
    states[int(w)] = (int(C), int(M), int(P), int(R))
ops = dict(x.split('=') for x in d['ops'].split())
# Instruction start offsets, as the Rocq [parse] makes them (fused tests are one instruction).
OPF = 1 << 31
starts = []; i = 0
while i < len(words):
    starts.append(i); o = words[i]
    if o in (0, 1): i += 3
    elif o in (5, 6, 14): i += 2
    elif o == 4:
        n = words[i + 3]; nxt = i + 4 + n
        fuse = nxt < len(words) and words[nxt] == 7 and words[nxt + 1] == words[i + 1] and \
            words[i + 2] in (int(ops['eq']), int(ops['consp']))
        i = nxt + 3 if fuse else nxt
    else: sys.exit('opcode %d' % o)
cutl = [cuts[s] for s in starts] + [cuts[len(words)]]
assert all(c >= 0 for c in cutl), cutl
def tagof(v): return v & 7
def is_ptr(v): return tagof(v) in (1, 3, 5, 6)
def coq_list(xs): return '[' + '; '.join('%d' % x for x in xs) + ']'
# Canonical states: slot 0 (return address) is current too; known pairs are dropped (not needed here).
inv = []
for s in starts:
    if s in states:
        C, M, P, R = states[s]
        inv.append('Some (mkS %s %d 0 %d)' % ('None' if C < 0 else '(Some %d)' % C, M | 1, R))
    else:
        inv.append('None')
kinds = []
for k, (v, cell) in enumerate(consts):
    kinds.append('if Z.eqb i %d then Some %s else' % (k, '(KPtr %d %d)' % (cell, tagof(v)) if is_ptr(v) else '(KImm %d)' % v))
cells = ['if Z.eqb a %d then Some %d else' % (cell, k) for k, (v, cell) in enumerate(consts)]
sha = hashlib.sha256(bytes(bytes_)).hexdigest()
out = f'''(** * {name}: bytes the real JIT emitted, and the checker's certificate.  Generated by
    capture/gen_instance.py from a checker dump; nothing here is trusted except that these are the
    bytes and bytecode of the run named in RESULTS.md.  Bytes SHA-256: {sha}. *)
From Stdlib Require Import NArith ZArith List Lia Bool.
From LinuxProcessSemantics.Examples.emitter_risks_ns Require Import CfDefs.
Import ListNotations.
Open Scope Z_scope.

Definition cap_bytes : list Z := {coq_list(bytes_)}.
Definition cap_words : list Z := {coq_list(words)}.
Definition cap_prims : prims := mkP {ops['eq']} {ops['cons']} {ops['hd']} {ops['tl']} {ops['consp']}.
Definition cap_cfg : cfg := {{|
  cbase := {d['base']};
  cbytes := cap_bytes;
  cframe := {d['frame']};
  ckinds := fun i => {' '.join(kinds)} None;
  h_alloc := {d['h_alloc']};
  c_unwind := {d['unwind']};
  c_arity_stub := {d['arity_stub']};
  c_arity := {d['arity']}
|}}.
Definition cap_cell_of : Z -> option Z := fun a => {' '.join(cells)} None.
Definition cap_parsed : option (list (nat * binstr)) := parse cap_prims 1000 cap_words 0.
Definition cap_prog : list binstr := match cap_parsed with Some l => map snd l | None => [] end.
Definition cap_cuts : list Z := {coq_list(cutl)}.
Definition cap_cut (i : nat) : Z := nth i cap_cuts (-1).
Definition cap_invl : list (option CS) := [{'; '.join(inv)}].
Definition cap_inv (i : nat) : option CS := nth i cap_invl None.
Definition cap_starts : list nat := [{'; '.join('%d%%nat' % s for s in starts)}].
Close Scope Z_scope.
'''
open(sys.argv[3], 'w').write(out)
print('instructions', len(starts), 'bytes', len(bytes_), 'sha256', sha)
