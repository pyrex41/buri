#!/usr/bin/env python3
"""Spike 9 item 1: the proof image and fetch/decode facts for the C checker's decode and run_block, bound
to the frozen check build's runtime.  Proof-side only: every fact is closed by a VM-checked cast, so a wrong
fact fails to compile.
- The proof image is the runtime with only p_memsz of its one LOAD set to p_filesz (spike 5/7's mkimage.py),
  which drops the 64 MiB arena and .bss.  Text, rodata and data bytes are identical.
- SourceMemImage.v from Theorem's elf_snapshot.py.
- s9bin_code.v: SF_/SD_ facts for each instruction of decode and run_block, the two jump tables as ro4
  facts, and an Ltac lookup [fd] from a pc literal to its facts, for the stepping tactics.
Usage: bin-gen.py RUNTIME EXDIR [ADDR:HEX ...]   (byte patches are for mutation testing only)"""
import hashlib, os, struct, subprocess, sys
W = os.environ.get('W', '/work-s9a')
sys.path.insert(0, W + '/tools')
import gen_fd_lemmas as g

FROZEN = '99300f3221ec53511d023f408e11ee6bd3b89f375ce36253d48a38a5a842955e'
RANGES = [(0x3e91e, 0x3ed02), (0x3d77a, 0x3dd92)]   # decode, run_block (nm -S)
JTS = [('JTd', 0x50de4, 53), ('JTr', 0x50da8, 15)]  # decode's switch on opcode-3, run_block's on kind-1
BASE = 0x10000
NS = 'LinuxProcessSemantics.Examples.s9bin_ns'

rt, ex = sys.argv[1:3]
patches = sys.argv[3:]
raw = open(rt, 'rb').read()
h = hashlib.sha256(raw).hexdigest()
if h != FROZEN:
    sys.exit('bin-gen: runtime is not the frozen check build: ' + h)
b = bytearray(raw)
phoff = struct.unpack_from('<Q', b, 32)[0]; phent, phnum = struct.unpack_from('<HH', b, 54)
loads = [phoff + i * phent for i in range(phnum) if struct.unpack_from('<I', b, phoff + i * phent)[0] == 1]
assert len(loads) == 1
o = loads[0]; filesz, memsz = struct.unpack_from('<QQ', b, o + 32)
struct.pack_into('<Q', b, o + 40, filesz)
assert all(o + 40 <= i < o + 48 for i in range(len(b)) if b[i] != raw[i])
for p in patches:
    va, hx = p.split(':'); hb = bytes.fromhex(hx); off = int(va, 16) - BASE
    if bytes(b[off:off + len(hb)]) == hb:
        sys.exit('bin-gen: patch changes no bytes: ' + p)
    b[off:off + len(hb)] = hb
img = '/tmp/s9bin_rt'
open(img, 'wb').write(b)
print('image sha256', hashlib.sha256(b).hexdigest())
os.makedirs(ex, exist_ok=True)
subprocess.run(['python3', W + '/tools/elf_snapshot.py', img, ex + '/SourceMemImage.v', '--prefix', 'SourceMemImage',
                '--module-name', 'Source', '--namespace', NS], check=True, stdout=subprocess.DEVNULL)
insns = []
for lo, hi in RANGES:
    pc = lo
    while pc < hi:
        w = struct.unpack_from('<I', b, pc - BASE)[0]
        insns.append((pc, w)); pc += 4 if w & 3 == 3 else 2
dec = g.decode_words(sorted({w for _, w in insns}), ['-Q', W + '/_build/default/theories/Riscv', 'LinuxProcessSemantics.Riscv'])
L = ['(** AUTO-GENERATED by spikes/emitter-phase3/bin-gen.py from the frozen check runtime.',
     '    Proof-side: every fact is closed by a VM-checked cast, so a wrong fact fails to compile. *)',
     'From Stdlib Require Import NArith ZArith List.',
     'From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase RiscvSemantics MemImageType.',
     'From %s Require Import SourceMemImage.' % NS,
     'From LinuxProcessSemantics.Riscv Require Import Prelude Instr Decode DecodeC.',
     'From LinuxProcessSemantics.Common Require Import PropExec StepTac.',
     'Import ListNotations.', 'Open Scope bv_scope.',
     'Definition source_segs := SourceMemImage_loaded_segments.',
     'Global Strategy 200 [source_segs].', 'Ltac vm_refl := vm_refl_bv.', '']
for pc, w in insns:
    assert dec[w] != 'None', hex(pc)
    a = f'{pc:x}'
    L.append(f'Lemma SF_{a} : fetch_word_wx source_segs 0x{a} = Some {w}. Proof. vm_refl. Qed.')
    L.append(f'Lemma SD_{a} : decode_any (Z_to_bv 32 {w}) = {dec[w]}. Proof. vm_refl. Qed.')
L.append('Definition ro4 (a v : word) : Prop := exists bs, PropExec.rdn source_segs (fun _ => None) a 4%nat = Some bs /\\ bytes_le_to_Z bs = bv_unsigned v.')
for name, jt, n in JTS:
    for i in range(n):
        a = jt + 4 * i; bs = b[a - BASE:a - BASE + 4]; v = struct.unpack('<I', bs)[0]
        lits = '; '.join(f'Z_to_bv 8 {x}' for x in bs)
        L.append(f'Lemma {name}_{i} : ro4 (Z_to_bv 64 {a}) (Z_to_bv 64 {v}). Proof. exists [{lits}]. split; vm_refl. Qed.')
# pc literal -> its facts, for automatic stepping
L.append('Ltac fd pc k :=\n  lazymatch pc with')
for pc, w in insns:
    a = f'{pc:x}'
    L.append(f'  | {pc}%Z => k SF_{a} SD_{a}')
L.append('  end.')
# jump-table address literal -> its ro4 fact
L.append('Ltac jtf a k :=\n  lazymatch a with')
for name, jt, n in JTS:
    for i in range(n):
        L.append(f'  | {jt + 4 * i}%Z => k {name}_{i}')
L.append('  end.')
open(ex + '/s9bin_code.v', 'w').write('\n'.join(L) + '\n')
print(len(insns), 'instructions')
