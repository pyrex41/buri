#!/usr/bin/env python3
"""Spike 9: writes CfCaptured9.v for shen.<shortnatters> from the hook's raw dump (SPIKE_RAW), the bytes
capture.c wrote, and a hand-written certificate. usage: gen_instance9.py RAW BIN CERT OUT

Nothing here is trusted except that these are the bytes, words and constant cells of the run: the checker
re-derives everything else, and a wrong certificate makes check_all fail.

Constants: the code's own constants keep their local index (0, 1). The sealed callee's slot is entry 3 of
the runtime's constant table (cbase is 4, so the code's constant 0 is entry 4); the bytecode names it by
that absolute index, and the instance uses 3 as its index in ckinds. Its tag (5, a procedure) is asserted
here, not read: the emitter emitted no resolve slow path, which it does only when the slot holds a
procedure (load_callee in jit.c), and Rel's r_tag premise states it of the state.
"""
import hashlib, sys
raw, binf, cert, out = sys.argv[1:5]
d = {}
for l in open(raw):
    k, *v = l.split()
    d[k] = v
base = int(d['base'][0]); frame = int(d['frame'][0]); arity = int(d['arity'][0])
words = [int(x) for x in d['words']]
cuts_w = [int(x) for x in d['cuts']]
consts = [tuple(int(y) for y in x.split(':')) for x in d['consts']]
bs = open(binf, 'rb').read()
starts = [i for i, c in enumerate(cuts_w[:-1]) if c >= 0]
cuts = [cuts_w[i] for i in starts] + [cuts_w[-1]]
SEALED_INDEX, SEALED_CELL = 3, consts[0][1] - 8  # entry cbase - 1 of the constant table
kinds, cells = [], []
for i, (v, a) in enumerate(consts):
    if v & 7 in (1, 3, 5, 6):
        kinds.append((i, 'KPtr %d %d' % (a, v & 7))); cells.append((a, i))
    else:
        kinds.append((i, 'KImm %d' % v))
kinds.append((SEALED_INDEX, 'KPtr %d 5' % SEALED_CELL)); cells.append((SEALED_CELL, SEALED_INDEX))
def opt(x): return 'None' if x == '-' else '(Some %s)' % x
invl = []
for l in open(cert):
    if l.startswith('#') or not l.strip(): continue
    C, M, P, R, K0, K1 = l.split()
    invl.append('Some (mkS %s %s %s %s %s %s)' % (opt(C), M, P, R, opt(K0), opt(K1)))
assert len(invl) == len(starts), (len(invl), len(starts))
kf = ' else '.join('if Z.eqb i %d then Some (%s)' % (i, k) for i, k in kinds) + ' else None'
cf = ' else '.join('if Z.eqb a %d then Some %d' % (a, i) for a, i in cells) + ' else None'
h = hashlib.sha256(bs).hexdigest()
o = open(out, 'w')
o.write('''(** * shen.<shortnatters> at 0.4: bytes the real JIT emitted, and a certificate.  Generated by
    capture/gen_instance9.py from the hook's raw dump; nothing here is trusted except that these are the
    bytes, bytecode and constant cells of the run named in RESULTS.md.  Bytes SHA-256: %s. *)
From Stdlib Require Import NArith ZArith List Lia Bool.
From LinuxProcessSemantics.Examples.emitter_p3_ns Require Import CfDefs.
Import ListNotations.
Open Scope Z_scope.

Definition sn_bytes : list Z := [%s].
Definition sn_words : list Z := [%s].
Definition sn_prims : prims := mkP 8 10 11 12 13.
Definition sn_cfg : cfg := {|
  cbase := %d;
  cbytes := sn_bytes;
  cframe := %d;
  ckinds := fun i => %s;
  h_alloc := %s;
  c_unwind := %s;
  c_arity_stub := %s;
  c_arity := %d
|}.
Definition sn_cell_of : Z -> option Z := fun a => %s.
Definition sn_parsed : option (list (nat * binstr)) := parse sn_prims 1000 sn_words 0.
Definition sn_prog : list binstr := match sn_parsed with Some l => map snd l | None => [] end.
Definition sn_cuts : list Z := [%s].
Definition sn_cut (i : nat) : Z := nth i sn_cuts (-1).
Definition sn_invl : list (option CS) := [%s].
Definition sn_inv (i : nat) : option CS := nth i sn_invl None.
Definition sn_starts : list nat := [%s].
Close Scope Z_scope.
''' % (h, '; '.join(str(b) for b in bs), '; '.join(map(str, words)), base, frame, kf,
       d['h_alloc'][0], d['unwind'][0], d['arity_stub'][0], arity, cf,
       '; '.join(map(str, cuts)), '; '.join(invl), '; '.join('%d%%nat' % s for s in starts)))
o.close()
print('bytes', h, 'instructions', len(starts))
