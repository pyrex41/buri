#!/usr/bin/env python3
"""Lean twin of tests/shen-jit/stage0_to_rocq.py: tokenize one stage 0 pair (<name>.forms,
<name>.sbc) into the generic tree `sx` of LeanJit/JitLowerStage0.lean. Trusted reader, same
tokenizer and real decoding as the Rocq one. Writes one Lean module whose theorem states the
file's (accepted, rejected, unreadable) counts, checked by the kernel (`decide +kernel`).

    stage0_to_lean.py STAGE0_DIR NAME OUT.lean ACCEPTED REJECTED UNREAD
"""
import struct, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'tests', 'shen-jit'))
from stage0_to_rocq import tokens, parse, is_number

def lean(x):
    if x[0] == 'list':
        return '(XList [' + ', '.join(lean(y) for y in x[1]) + '])'
    if x[0] == 'str':
        return '(XStr [' + ', '.join('%d' % b for b in x[1]) + '])'
    a = x[1]
    if is_number(a):
        if any(ch in a for ch in '.eE'):
            return '(XReal %d)' % struct.unpack('<Q', struct.pack('<d', float(a)))[0]
        return '(XInt (%d))' % int(a)
    assert '"' not in a and '\\' not in a, a
    return '(XSym "%s")' % a

def main(d, name, out, a, r, u):
    forms = parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    sbc = parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    ident = name.replace('-', '_')
    with open(out, 'w') as f:
        f.write('-- Generated by lean-jit/tools/stage0_to_lean.py from %s.forms and %s.sbc.\n' % (name, name))
        f.write('import LeanJit.JitLowerStage0\nopen JitLowerStage0 JitLowerStage0.sx\nset_option maxRecDepth 100000\n')
        f.write('namespace S0_%s\n' % ident)
        for i, x in enumerate(forms):
            f.write('def f%d : sx := %s\n' % (i, lean(x)))
        for i, x in enumerate(sbc):
            f.write('def s%d : sx := %s\n' % (i, lean(x)))
        f.write('def forms : List sx := [%s]\n' % ', '.join('f%d' % i for i in range(len(forms))))
        f.write('def sbc : List sx := [%s]\n' % ', '.join('s%d' % i for i in range(len(sbc))))
        f.write('theorem counts_ok : counts forms sbc = (%s, %s, %s) := by decide +kernel\n' % (a, r, u))
        f.write('end S0_%s\n' % ident)

if __name__ == '__main__':
    main(*sys.argv[1:7])
