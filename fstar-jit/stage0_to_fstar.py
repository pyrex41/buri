#!/usr/bin/env python3
"""Turn one stage 0 file pair (<name>.forms, <name>.sbc) into F* data for Buri.JitLowerStage0.

The F* twin of tests/shen-jit/stage0_to_rocq.py, and trusted in the same way: it only tokenizes
(the tokenizer and real-to-bits step are copied from that file unchanged) and prints the generic
tree `sx`. F* turns the trees into KLambda values and code objects and runs the checker.

    stage0_to_fstar.py STAGE0_DIR NAME OUTDIR [ACCEPTED REJECTED UNPARSED]

Writes OUTDIR/Stage0.Data.<Id>.fst (the trees) and, given the expected counts,
OUTDIR/Stage0.Judge.<Id>.fst (assert_norm that the judge's counts are those).
"""
import struct, sys, os

def tokens(text):
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in ' \n\t\r':
            i += 1
        elif c in '()':
            yield c; i += 1
        elif c == '"':
            j, out = i + 1, []
            while text[j] != '"':
                if text[j] == '\\':
                    k = text[j + 1]
                    if k == 'x':
                        out.append(int(text[j + 2:j + 4], 16)); j += 4
                    else:
                        out.append(ord(k)); j += 2
                else:
                    out.append(ord(text[j])); j += 1
            yield ('str', out); i = j + 1
        else:
            j = i
            while j < n and text[j] not in ' \n\t\r()"':
                j += 1
            yield ('atom', text[i:j]); i = j

def parse(toks):
    stack = [[]]
    for t in toks:
        if t == '(':
            stack.append([])
        elif t == ')':
            x = stack.pop(); stack[-1].append(('list', x))
        else:
            stack[-1].append(t)
    assert len(stack) == 1
    return stack[0]

def is_number(a):
    return a[0].isdigit() or (len(a) > 1 and a[0] in '+-.' and (a[1].isdigit() or a[1] == '.'))

def fstar(x):
    if x[0] == 'list':
        return '(XList [' + ';'.join(fstar(y) for y in x[1]) + '])'
    if x[0] == 'str':
        return '(XStr [' + ';'.join('%d' % b for b in x[1]) + '])'
    a = x[1]
    if is_number(a):
        if any(ch in a for ch in '.eE'):
            bits = struct.unpack('<Q', struct.pack('<d', float(a)))[0]
            return '(XReal %d)' % bits
        return '(XInt (%d))' % int(a)
    assert '"' not in a and '\\' not in a, a
    return '(XSym "%s")' % a

def ident(name):
    return ''.join(p[:1].upper() + p[1:] for p in name.replace('_', '-').split('-'))

def main(d, name, out, *expected):
    forms = parse(tokens(open('%s/%s.forms' % (d, name)).read()))
    sbc = parse(tokens(open('%s/%s.sbc' % (d, name)).read()))
    i = ident(name)
    with open(os.path.join(out, 'Stage0.Data.%s.fst' % i), 'w') as f:
        f.write('(* Generated by stage0_to_fstar.py from %s.forms and %s.sbc. *)\n' % (name, name))
        f.write('module Stage0.Data.%s\nopen Buri.JitLowerStage0\n' % i)
        f.write('let forms : list sx = [%s]\n' % ';\n '.join(fstar(x) for x in forms))
        f.write('let sbc : list sx = [%s]\n' % ';\n '.join(fstar(x) for x in sbc))
    if expected:
        a, r, u = expected
        with open(os.path.join(out, 'Stage0.Judge.%s.fst' % i), 'w') as f:
            f.write('(* Generated by stage0_to_fstar.py: the judge on %s, against the recorded counts. *)\n' % name)
            f.write('module Stage0.Judge.%s\nopen Buri.JitLowerStage0\n' % i)
            f.write('let _ = assert_norm (counts Stage0.Data.%s.forms Stage0.Data.%s.sbc == (%s, %s, %s))\n' % (i, i, a, r, u))

if __name__ == '__main__':
    main(*sys.argv[1:])
