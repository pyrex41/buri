(* Layout facts of the pinned image (ground): 63-bit fixnums with one tag
   bit (n << 1); 4-bit lowtags; NIL is a list pointer (and an other pointer
   one word up, early-objdef.lisp); characters range over 0..#x10FFFF
   including the surrogate block, which is wider than the VALUE-MODEL string
   profile of Unicode scalar values. *)
Lemma sbcl_layout_facts :
  img_n_fixnum_tag_bits = 1 /\ img_fixnum_tag_mask = 1 /\ img_n_fixnum_bits = 63 /\
  img_most_positive_fixnum = 2 ^ 62 - 1 /\ img_most_negative_fixnum = - 2 ^ 62 /\
  img_lowtag_mask = 2 ^ img_n_lowtag_bits - 1 /\
  img_nil_value mod 2 ^ img_n_lowtag_bits = img_list_pointer_lowtag /\
  src_list_pointer_lowtag + img_n_word_bytes = src_other_pointer_lowtag /\
  img_char_code_limit = 1114112 /\ img_cons_size = 2 /\ img_cons_car_slot = 0 /\
  img_cons_cdr_slot = 1 /\ img_double_float_value_slot = 1 /\ img_vector_data_offset = 2.
Proof. vm_compute. repeat split; reflexivity. Qed.

End SbclRepr.
