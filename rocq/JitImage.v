Definition files_val (fs : list (string * list S0.sx)) : list (string * list val) :=
 map (fun '(f, xs) => (f, map S0.to_val xs)) fs.

Definition files_ok (c : ctx) (fs : list (string * list val)) : bool :=
 forallb (fun '(_, xs) => match snd (tally c xs) with [] => true | _ => false end) fs.

(* The lane's check: the image parses, and every definition of every file is Match. *)
Definition code_check (ws : list N) (fs : list (string * list val)) : bool :=
 match image_of ws with Some (_, c) => files_ok c fs | None => false end.

Theorem code_check_sound : forall ws fs, code_check ws fs = true ->
  exists h c, image_of ws = Some (h, c) /\
  forall fl xs x, In (fl, xs) fs -> In x xs ->
  exists g code k, x = VPair (VSym S_defun) (VPair (VSym g) (VPair code VNil))
    /\ build_code prim_tree 64 code = LOk k /\ fn_code c g = Some k.
Proof.
 unfold code_check. intros ws fs H. destruct (image_of ws) as [[h c]|]; [|discriminate].
 exists h, c. split; [reflexivity|]. intros fl xs x Hf Hx.
 unfold files_ok in H. rewrite forallb_forall in H. specialize (H _ Hf). simpl in H.
 destruct (tally c xs) as [n bad] eqn:T. destruct bad; [|discriminate]. simpl in H.
 destruct (tally_sound c xs n T) as [_ Hm]. destruct (Hm x Hx) as [g Hg].
 destruct (check_def_sound c x g Hg) as (code & k & E & B & F). exists g, code, k. auto.
Qed.

(* ---------- measurements made by Rocq on the same image (census, not proof) ---------- *)
Definition defname (x : val) : option positive := match x with
 | VPair _ (VPair (VSym g) _) => Some g | _ => None end.

(* The closure in symbol s's function cell: its absolute word. *)
Definition fn_clo (c : ctx) (s : positive) : option N :=
 match tget s (c_symcell c) with
 | Some k => match rd (c_mem c) (c_cb c + 2 * k + 1) with
   | Some fv => deref (c_mem c) (c_hb c) (c_starts c) fv 5 6
   | None => None end
 | None => None end.

(* Code objects reachable from a code pointer, nested codes included: their absolute words. *)
Fixpoint reach (c : ctx) (fuel : nat) (v : N) (acc : list N) : list N :=
 match fuel with O => acc | S f =>
 match deref (c_mem c) (c_hb c) (c_starts c) v 1 8 with
 | None => acc
 | Some a =>
   let cb := get (c_mem c) (a + 4) in let nk := get (c_mem c) (a + 5) in let nc := get (c_mem c) (a + 6) in
   fold_left (fun acc i => reach c f (get (c_mem c) (c_kb c + cb + nk + i)) acc) (seqN 0 (N.to_nat nc)) (a :: acc)
 end end.

Definition reached (c : ctx) (xs : list val) : tree unit :=
 fold_left (fun t x => match defname x with
   | Some g => match fn_clo c g with
     | Some a => fold_left (fun t a => tset (key a) tt t) (reach c 64 (get (c_mem c) (a + 2)) []) t
     | None => t end
   | None => t end) xs Leaf.
Definition in_tree (a : N) (t : tree unit) : bool := match tget (key a) t with Some _ => true | None => false end.

Definition raw_of (c : ctx) (g : positive) : option N :=
 match find (fun '(s, _, _) => Pos.eqb s g) (symbols (c_mem c) (c_hb c) (c_starts c) (c_objs c)) with
 | Some (_, _, w) => Some w | None => None end.
Definition sealed_bit (c : ctx) (g : positive) : bool :=
 match raw_of c g with Some w => N.testbit w 58 | None => false end.

(* Per file: (file, definitions, how many of their names carry the sealed bit). *)
Definition sealed_by_file (c : ctx) (fs : list (string * list val)) : list (string * nat * nat) :=
 map (fun '(fl, xs) =>
   let gs := flat_map (fun x => match defname x with Some g => [g] | None => [] end) xs in
   (fl, List.length gs, List.length (filter (sealed_bit c) gs))) fs.

Definition sym_list (c : ctx) := symbols (c_mem c) (c_hb c) (c_starts c) (c_objs c).
Definition cell_word (c : ctx) (k : N) : N := get (c_mem c) (c_cb c + k).

(* What a cell slot holds: 0 closure, 1 unbound (the immediate 26), 2 anything else. *)
Definition slot_kind (v : N) : nat := if N.eqb (tag v) 5 then 0%nat else if N.eqb v 26 then 1%nat else 2%nat.

(* A name, for printing. *)
Definition vname (v : option val) : string := match v with
 | Some (VSym p) => string_of_list_ascii (map ascii_of_N (text_of_sym p)) | _ => "?"%string end.

Record census := Census {
 cn_symbols : nat; cn_sealed : nat;                 (* symbols; those with the sealed bit *)
 cn_fn_closures : nat; cn_values_bound : nat;       (* function cells holding a closure; value cells not unbound *)
 cn_codes : nat; cn_codes_unreached : nat;          (* code objects; not reached from the 955 *)
 cn_unreached_names : list string;
 cn_closures : nat; cn_clo_in_fn : nat; cn_clo_in_val : nat;
 cn_clo_other : nat; cn_clo_other_reached : nat; cn_clo_other_captures : nat }.

Definition census_of (c : ctx) (xs : list val) : census :=
 let syms := sym_list c in
 let fncl := flat_map (fun '(_, k, _) => let v := cell_word c (2 * k + 1) in
                         if N.eqb (tag v) 5 then [c_hb c + woff v] else []) syms in
 let valcl := flat_map (fun '(_, k, _) => let v := cell_word c (2 * k) in
                         if N.eqb (tag v) 5 then [c_hb c + woff v] else []) syms in
 let mem_l a l := existsb (N.eqb a) l in
 let r := reached c xs in
 let codes := filter (fun '(_, t) => N.eqb t 8) (c_objs c) in
 let unr := filter (fun '(o, _) => negb (in_tree (c_hb c + o) r)) codes in
 let clos := map (fun '(o, _) => c_hb c + o) (filter (fun '(_, t) => N.eqb t 6) (c_objs c)) in
 let other := filter (fun a => negb (mem_l a fncl)) clos in
 Census (List.length syms) (List.length (filter (fun '(_, _, w) => N.testbit w 58) syms))
   (List.length fncl)
   (List.length (filter (fun '(_, k, _) => negb (N.eqb (cell_word c (2 * k)) 26)) syms))
   (List.length codes) (List.length unr)
   (map (fun '(o, _) => vname (dval c 64 (get (c_mem c) (c_hb c + o + 7)))) unr)
   (List.length clos) (List.length fncl) (List.length valcl) (List.length other)
   (List.length (filter (fun a => match deref (c_mem c) (c_hb c) (c_starts c) (get (c_mem c) (a + 2)) 1 8 with
                                  | Some b => in_tree b r | None => false end) other))
   (List.length (filter (fun a => negb (N.eqb (hsize (get (c_mem c) a)) 0)) other)).

(* The facts share's HT and HP are about, for one name: (sealed bit, what its function cell holds,
   and whether its function cell's code is Match against its stage 0 definition, if it has one). *)
Definition name_facts (c : ctx) (xs : list val) (g : positive) : bool * nat * option bool :=
 let k := match tget g (c_symcell c) with Some k => slot_kind (cell_word c (2 * k + 1)) | None => 2%nat end in
 let m := match find (fun x => match defname x with Some h => Pos.eqb h g | None => false end) xs with
   | Some x => Some (match check_def c x with Match _ => true | _ => false end)
   | None => None end in
 (sealed_bit c g, k, m).

(* The two image mutants (the word positions are found, not given): name g's code object with its
   arity word raised by one, and with bit 1 of its first bytecode byte flipped. *)
Definition code_word (c : ctx) (g : positive) : option N :=
 match fn_clo c g with Some a => deref (c_mem c) (c_hb c) (c_starts c) (get (c_mem c) (a + 2)) 1 8 | None => None end.
Definition mut_arity (ws : list N) (g : positive) : option mem :=
 match image_of ws with
 | Some (_, c) => match code_word c g with
   | Some a => Some (tset (key (a + 2)) (get (c_mem c) (a + 2) + 1) (c_mem c)) | None => None end
 | None => None end.
Definition mut_byte (ws : list N) (g : positive) : option mem :=
 match image_of ws with
 | Some (_, c) => match code_word c g with
   | Some a => match deref (c_mem c) (c_hb c) (c_starts c) (get (c_mem c) (a + 8)) 1 2 with
     | Some b => Some (tset (key (b + 1)) (N.lxor (get (c_mem c) (b + 1)) 2) (c_mem c)) | None => None end
   | None => None end
 | None => None end.
(* g's verdict in a mutated image: Differ, Undecoded or Unbuilt means the mutant is caught. The
   mutated image must still parse: a mutant that breaks parsing is not counted as caught, so a
   caught mutant has gone through check_def. *)
Definition mut_caught (om : option mem) (n : nat) (xs : list val) (g : positive) : bool :=
 match om with
 | None => false
 | Some m => match parse_image m (N.of_nat n) with
   | None => false
   | Some (_, c) => match find (fun x => match defname x with Some h => Pos.eqb h g | None => false end) xs with
     | Some x => match check_def c x with Match _ => false | _ => true end
     | None => false end end end.
